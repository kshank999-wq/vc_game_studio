// ---------------------------------------------------------------- generation

const thingFields = (t: IrThing): Record<string, string> => ({
  key: gd(t.ident.key),
  code: gd(t.code),
  display_name: gd(t.name),
  description: gd(t.notes),
  details: gd(Object.fromEntries(Object.entries(t.fields).filter(([k]) => k !== 'seconds' && k !== 'shots'))),
});

export const generateGodot = (ir: HandoffIR, outputPath: string, options: GenerateOptions = {}): EngineOutput => {
  const placeholders = options.placeholderScenes !== false;
  const root = outputPath.replace(/^res:\/\//, '').replace(/\/+$/, '') || 'vcgs/generated';
  const files: GeneratedFile[] = [...runtime(), ...sceneRuntime(), ...(ir.levels.length ? levelRuntime() : [])];
  const elements: ElementOutput[] = [];
  const add = (path: string, content: string) => {
    files.push({ path: `${root}/${path}`, content: content.endsWith('\n') ? content : `${content}\n`, kind: 'generated' });
    return `${root}/${path}`;
  };
  const row = (e: Omit<ElementOutput, 'fingerprint'>, data: unknown) =>
    elements.push({ ...e, fingerprint: fingerprint(`${VERSION}:${JSON.stringify(data)}`) });

  // Scenes: one flow controller each.
  for (const s of ir.scenes) {
    const branches = s.branches.map((b) => ({
      label: b.label,
      from: b.from,
      events: b.events.map(eventData),
      rejoin: b.rejoin ?? -1,
      ...(b.when ? { when: b.when } : {}),
      ...(b.effects ? { effects: b.effects } : {}),
      ...(b.after ? { after: b.after } : {}),
      ...(b.hide ? { hide: true } : {}),
    }));
    const path = add(
      `scenes/${s.ident.key}.gd`,
      [
        HEADER,
        `class_name Scene${s.ident.type}`,
        `extends VCGSSceneFlow`,
        `## ${s.code} ${s.name} · ${s.slug}`,
        ...(s.summary ? [`## ${s.summary}`] : []),
        '',
        `const KEY := ${gd(s.ident.key)}`,
        `const CODE := ${gd(s.code)}`,
        `const CONTENTS := ${gd(s.contents)}`,
        `const LOCATION := ${gd(s.location ?? '')}`,
        `const EVENTS := ${gd(s.main.map(eventData))}`,
        `const BRANCHES := ${gd(branches)}`,
        '## The routes out on the story graph, in order; the first whose conditions hold is taken.',
        `const EXITS := ${gd(s.exits)}`,
        `const ONWARD := ${gd(s.onward ?? '')}`,
        '',
        'func scene_key() -> String:',
        '\treturn KEY',
        '',
        'func location_key() -> String:',
        '\treturn LOCATION',
        '',
        'func events() -> Array:',
        '\treturn EVENTS',
        '',
        'func branches() -> Array:',
        '\treturn BRANCHES',
        '',
        'func next_node() -> String:',
        '\tvar game := _game()',
        '\tfor exit in EXITS:',
        '\t\tif VCGSRuleEngine.check(exit.get("when", {}), game):',
        '\t\t\tVCGSRuleEngine.apply(exit.get("effects", []), game)',
        '\t\t\treturn exit["to"]',
        '\treturn ONWARD',
      ].join('\n'),
    );
    // A placeholder scene to run it in, with everything in it stood in for.
    const tscn = placeholders ? sceneTscn(ir, s, root) : null;
    const tscnPath = tscn ? add(`scenes/${s.ident.key}.tscn`, tscn) : null;
    row(
      {
        id: s.id,
        label: `${s.code} ${s.name}`.trim(),
        symbol: 'scene',
        group: 'Story',
        generates: `Scene flow controller · ${s.main.length} event${s.main.length === 1 ? '' : 's'}${s.branches.length ? ` · ${s.branches.length} branch${s.branches.length === 1 ? '' : 'es'}` : ''}${tscn ? ' · placeholder scene' : ''}`,
        files: tscnPath ? [path, tscnPath] : [path],
      },
      { s, tscn },
    );
  }

  for (const c of ir.cinematics) {
    const path = add(
      `cinematics/${c.ident.key}.tres`,
      tres('VCGSCinematic', 'cinematic.gd', {
        ...thingFields(c),
        seconds: gd(Number(c.fields.seconds ?? 0)),
        shots: gd(Number(c.fields.shots ?? 1)),
        ...(c.shots ? { shot_list: gd(c.shots.map((s) => ({ ...s, line: s.line ?? '' }))) } : {}),
        skippable: gd(c.fields.skippable !== 'Not skippable'),
      }),
    );
    row({ id: c.id, label: `${c.code} ${c.name}`.trim(), symbol: 'cinematic', group: 'Story', generates: c.shots ? `Cinematic resource · shot list (${c.shots.length})` : 'Cinematic resource · shots · camera notes', files: [path] }, c);
  }

  for (const c of ir.choices) {
    const path = add(
      `choices/${c.ident.key}.gd`,
      [
        HEADER,
        `class_name Choice${c.ident.type}`,
        'extends RefCounted',
        '',
        `const KEY := ${gd(c.ident.key)}`,
        `const CODE := ${gd(c.code)}`,
        `const SCENE := ${gd(c.scene ?? '')}`,
        `const PROMPT := ${gd(c.prompt)}`,
        '## Each option and the story node it leads to ("" carries on in the scene).',
        `const OPTIONS := ${gd(c.options.map((o) => ({ key: o.key, label: o.label, to: o.to ?? '', ...(o.when ? { when: o.when } : {}), ...(o.effects ? { effects: o.effects } : {}), ...(o.after ? { after: o.after } : {}), ...(o.hide ? { hide: true } : {}) })))}`,
        '## The choice is offered at all only when this holds.',
        `const AVAILABLE := ${gd(c.available ?? {})}`,
        '',
        'static func available(game: VCGSGameState) -> bool:',
        '\treturn VCGSRuleEngine.check(AVAILABLE, game)',
        '',
        '## The indexes into OPTIONS that can be picked right now: their conditions',
        '## hold, and they are not gone or locked once picked.',
        'static func offered(game: VCGSGameState) -> Array:',
        '\tvar out: Array = []',
        '\tfor i in OPTIONS.size():',
        '\t\tvar o := VCGSRuleEngine.offer(OPTIONS[i], option_key(i), game)',
        '\t\tif not o.is_empty() and o["available"]:',
        '\t\t\tout.append(i)',
        '\treturn out',
        '',
        '## Every option in the list now, with whether it can be picked: { index, label, available, why }.',
        'static func listed(game: VCGSGameState) -> Array:',
        '\tvar out: Array = []',
        '\tfor i in OPTIONS.size():',
        '\t\tvar o := VCGSRuleEngine.offer(OPTIONS[i], option_key(i), game)',
        '\t\tif not o.is_empty():',
        '\t\t\tout.append({ "index": i, "label": OPTIONS[i]["label"], "available": o["available"], "why": o["why"] })',
        '\treturn out',
        '',
        'static func option_key(option: int) -> String:',
        '\treturn "%s:%s" % [KEY, OPTIONS[option]["key"]]',
        '',
        '## Records the pick, does what it does, and returns where it leads.',
        'static func choose(option: int, game: VCGSGameState) -> String:',
        '\tif option < 0 or option >= OPTIONS.size():',
        '\t\treturn ""',
        '\tvar o := VCGSRuleEngine.offer(OPTIONS[option], option_key(option), game)',
        '\tif o.is_empty() or not o["available"]:',
        '\t\treturn ""',
        '\tgame.remember_choice(KEY, OPTIONS[option]["label"])',
        '\tgame.mark_picked(option_key(option))',
        '\tVCGSRuleEngine.apply(OPTIONS[option].get("effects", []), game)',
        '\treturn OPTIONS[option]["to"]',
      ].join('\n'),
    );
    row({ id: c.id, label: `${c.code} ${c.name}`.trim(), symbol: 'choice', group: 'Story', generates: `Choice script · ${c.options.length} option${c.options.length === 1 ? '' : 's'}`, files: [path] }, c);
  }

  const storyData = { spine: ir.spine, branches: ir.branches, subplots: ir.subplots, arcs: ir.arcs };
  const storyPath = add(
    'story/story_graph.gd',
    [
      HEADER,
      'class_name VCGSStory',
      'extends RefCounted',
      `## ${ir.project.name}: the spine in order, branches, subplots and character arcs.`,
      '',
      `const SPINE := ${gd(ir.spine.map((n) => ({ key: n.key, kind: n.kind, name: n.name })))}`,
      `const BRANCHES := ${gd(ir.branches)}`,
      `const SUBPLOTS := ${gd(ir.subplots.map((s) => ({ key: s.key, name: s.name, from: s.from, to: s.to, beats: s.beats.map((b) => b.key) })))}`,
      `const ARCS := ${gd(Object.fromEntries(ir.arcs.map((a) => [a.character, a.events.map((e) => ({ polarity: e.polarity, name: e.name, tied_to: e.tiedTo ?? '' }))])))}`,
      `const SCENES := ${gd(Object.fromEntries(ir.scenes.map((s) => [s.ident.key, `res://${root}/scenes/${s.ident.key}.gd`])))}`,
      '',
      '## Where the story starts, and every node on the graph with where it goes:',
      '## routes in order (the first whose conditions hold), else onward along the spine.',
      `const START := ${gd(ir.graph.find((n) => n.kind === 'begin')?.key ?? '')}`,
      `const NODES := ${gd(storyNodes(ir, root))}`,
    ].join('\n'),
  );
  const playStory = placeholders ? add('play_story.tscn', storyTscn(ir, root)) : null;
  row(
    {
      id: 'story',
      label: 'Story graph',
      symbol: 'plotPoint',
      group: 'Story',
      generates: `Spine (${ir.spine.length}) · branches · subplots · arcs${playStory ? ' · play_story.tscn' : ''}`,
      files: playStory ? [storyPath, playStory] : [storyPath],
    },
    { storyData, graph: ir.graph, playStory: !!playStory },
  );

  // People and words.
  for (const c of ir.characters) {
    const path = add(
      `characters/${c.ident.key}.tres`,
      tres('VCGSCharacter', 'character.gd', {
        key: gd(c.ident.key),
        code: gd(c.code),
        display_name: gd(c.name),
        description: gd(c.description),
        role: gd(c.role),
        arc: gd(c.arc),
        color: color(c.color),
        codex: gd(c.codex),
      }),
    );
    row({ id: c.id, label: c.name, symbol: 'character', group: 'People + words', generates: 'Character resource · arc', files: [path] }, c);
  }

  // A line with emphasis carries it as BBCode for a RichTextLabel; a dual line names the one it is spoken with.
  const bbcode = (text: string) => markupInline(text, (run, st) => `${st.bold ? '[b]' : ''}${st.italic ? '[i]' : ''}${st.underline ? '[u]' : ''}${run}${st.underline ? '[/u]' : ''}${st.italic ? '[/i]' : ''}${st.bold ? '[/b]' : ''}`);
  const table = Object.fromEntries(
    ir.lines.map((l) => [l.id, { scene: l.scene, speaker: l.speaker ?? '', text: l.text, direction: l.direction, vo: l.vo, ...(l.styled ? { bbcode: bbcode(l.styled) } : {}), ...(l.dual ? { dual_with: l.dual } : {}) }]),
  );
  const dialoguePath = add(
    'dialogue/dialogue_table.gd',
    [
      HEADER,
      'class_name VCGSDialogue',
      'extends RefCounted',
      '',
      `const LINES := ${gd(table)}`,
      '',
      '## Speaker keys to the names shown on screen.',
      `const SPEAKERS := ${gd(Object.fromEntries(ir.characters.map((c) => [c.ident.key, c.name])))}`,
      '',
      'static func line(line_id: String) -> Dictionary:',
      '\treturn LINES.get(line_id, {})',
    ].join('\n'),
  );
  // Production files live under a .gdignore so Godot doesn't import them.
  add('production/.gdignore', '');
  const csv = (cells: string[]) => cells.map((c) => (/[",\n]/.test(c) ? `"${c.replace(/"/g, '""')}"` : c)).join(',');
  const voPath = add(
    'production/vo_cues.csv',
    [csv(['line', 'scene', 'speaker', 'text', 'direction', 'status']), ...ir.lines.filter((l) => l.vo !== 'none').map((l) => csv([l.id, l.scene, l.speaker ?? '', l.text, l.direction, l.vo]))].join('\n'),
  );
  row({ id: 'dialogue', label: `Dialogue (${ir.lines.length} line${ir.lines.length === 1 ? '' : 's'})`, symbol: 'dialogue', group: 'People + words', generates: 'Dialogue table · VO cue list', files: [dialoguePath, voPath] }, ir.lines);

  // The world.
  for (const o of ir.objects) {
    if (o.kind === 'puzzle') {
      const path = add(`puzzles/${o.ident.key}.tres`, tres('VCGSPuzzle', 'puzzle.gd', { key: gd(o.ident.key), code: gd(o.code), display_name: gd(o.name), description: gd(o.notes), details: gd(o.fields), states: gd(o.states) }));
      row({ id: o.id, label: o.name, symbol: 'puzzle', group: 'World', generates: 'Puzzle resource · hints · fail state', files: [path] }, o);
      continue;
    }
    const interactions = o.interactions.map((i) => ({
      verb: i.verb,
      ...(i.when ? { when: i.when } : {}),
      ...(i.becomes ? { becomes: i.becomes } : {}),
      ...(i.sets ? { sets: { flag: i.sets.flag, value: i.sets.value } } : {}),
      ...(i.fires ? { fires: i.fires } : {}),
      ...(i.requires ? { requires: i.requires } : {}),
      ...(i.effects ? { effects: i.effects } : {}),
    }));
    const path = add(
      `objects/${o.ident.key}.gd`,
      [
        HEADER,
        `class_name Object${o.ident.type}`,
        'extends VCGSInteractable',
        `## ${o.code} ${o.name}`.trim(),
        ...(o.fields.assetNotes ? [`## Asset notes: ${o.fields.assetNotes}`] : []),
        '',
        `const KEY := ${gd(o.ident.key)}`,
        `const STATES := ${gd(o.states)}`,
        `const INTERACTIONS := ${gd(interactions)}`,
        '',
        'func object_key() -> String:',
        '\treturn KEY',
        '',
        'func states() -> Array:',
        '\treturn STATES',
        '',
        'func initial_state() -> String:',
        `\treturn ${gd(o.initial ?? '')}`,
        '',
        'func interactions() -> Array:',
        '\treturn INTERACTIONS',
      ].join('\n'),
    );
    row({ id: o.id, label: o.name, symbol: 'object', group: 'World', generates: o.states.length ? 'Interactable · state machine' : 'Interactable stub', files: [path] }, o);
  }
  for (const [list, symbol, cls, folder, label] of [
    [ir.items, 'inventory', 'VCGSItem', 'items', 'Item definition'],
    [ir.locations, 'environment', 'VCGSLocation', 'locations', 'Location data · ambience cues'],
  ] as const) {
    for (const t of list) {
      const path = add(`${folder}/${t.ident.key}.tres`, tres(cls, `${cls.replace('VCGS', '').toLowerCase()}.gd`, thingFields(t)));
      row({ id: t.id, label: t.name, symbol, group: 'World', generates: label, files: [path] }, t);
    }
  }
  // Design definitions: a Resource each, for the game's codex, quest log or tuning.
  for (const d of DESIGN_LISTS) {
    const cls = `VCGS${d.type[0]!.toUpperCase()}${d.type.slice(1)}`;
    for (const t of ir[d.list]) {
      const path = add(`${d.list}/${t.ident.key}.tres`, tres(cls, `${d.type}.gd`, thingFields(t)));
      row({ id: t.id, label: `${t.code} ${t.name}`.trim(), symbol: d.type, group: d.group, generates: `${cls} resource`, files: [path] }, t);
    }
  }

  // Logic: one rules script for every flag, trigger and gate.
  const rulesPath = `${root}/logic/rules.gd`;
  const gates = ir.triggers.filter((t) => t.kind === 'gate');
  add(
    'logic/rules.gd',
    [
      HEADER,
      'class_name VCGSRules',
      'extends RefCounted',
      '',
      '## Every state the game remembers: its values and where it starts.',
      `const FLAGS := ${gd(Object.fromEntries(ir.flags.map((f) => [f.ident.key, { values: f.values, initial: f.initial }])))}`,
      '',
      '## Where each object starts.',
      `const OBJECTS := ${gd(Object.fromEntries(ir.objects.filter((o) => o.kind === 'object' && o.initial).map((o) => [o.ident.key, o.initial!])))}`,
      '',
      '## Each trigger: its words, and the rule that fires it (once) and what it does.',
      `const TRIGGERS := ${gd(Object.fromEntries(ir.triggers.filter((t) => t.kind === 'trigger').map((t) => [t.ident.key, { fires_when: t.condition, does: t.effect, ...(t.sets ? { sets: t.sets } : {}), ...(t.rule ? { rule: t.rule } : {}), ...(t.effects ? { effects: t.effects } : {}) }])))}`,
      '',
      `const GATES := ${gd(Object.fromEntries(gates.map((g) => [g.ident.key, { needs: g.condition, holds: g.effect, ...(g.rule ? { rule: g.rule } : {}) }])))}`,
      '',
      '## Each puzzle: what solves it and what solving it does.',
      `const PUZZLES := ${gd(Object.fromEntries(ir.objects.filter((o) => o.kind === 'puzzle').map((o) => [o.ident.key, { ...(o.solvedWhen ? { solved_when: o.solvedWhen } : {}), ...(o.effects ? { effects: o.effects } : {}) }])))}`,
      '',
      '## Each quest: its name and goal, for a quest log; under way once "starts"',
      '## holds (at once without it), done when "completes" holds, paying its "reward".',
      `const QUESTS := ${gd(Object.fromEntries(ir.quests.map((q) => [q.ident.key, { name: q.name, goal: q.fields.goal ?? '', ...(q.byEffect ? { by_effect: true } : {}), ...(q.starts ? { starts: q.starts } : {}), ...(q.completes ? { completes: q.completes } : {}), ...(q.reward ? { reward: q.reward } : {}) }])))}`,
      '',
      '## Each encounter: its name, text and fields (enemies, weakness) for a codex,',
      '## when a win counts, what winning and losing do, and what a loss leads to',
      '## ("retry", "gameOver" or "carryOn").',
      `const ENCOUNTERS := ${gd(Object.fromEntries(ir.encounters.map((e) => [e.ident.key, { name: e.name, text: e.notes, details: e.fields, ...(e.winWhen ? { win_when: e.winWhen } : {}), ...(e.onWin ? { on_win: e.onWin } : {}), ...(e.onLose ? { on_lose: e.onLose } : {}), loss: e.loss }])))}`,
      '',
      '## Each character with a codex entry: their name and what the codex says once met.',
      `const CHARACTERS := ${gd(Object.fromEntries(ir.characters.filter((c) => c.codex.trim()).map((c) => [c.ident.key, { name: c.name, codex: c.codex }])))}`,
      '',
      '## Each location with a codex entry: its name and what the codex says once visited.',
      `const LOCATIONS := ${gd(Object.fromEntries(ir.locations.filter((l) => l.fields.codex).map((l) => [l.ident.key, { name: l.name, codex: l.fields.codex! }])))}`,
      '',
      '## Each object with a codex entry: its name and what the codex says once used.',
      `const OBJECT_ENTRIES := ${gd(Object.fromEntries(ir.objects.filter((o) => o.kind === 'object' && o.fields.codex).map((o) => [o.ident.key, { name: o.name, codex: o.fields.codex! }])))}`,
      '',
      '## Each item with a codex entry: its name and what the codex says once found.',
      `const ITEMS := ${gd(Object.fromEntries(ir.items.filter((i) => (i.fields.codex ?? '').trim()).map((i) => [i.ident.key, { name: i.name, codex: i.fields.codex!.trim() }])))}`,
      '',
      '## Each lore entry: its name and text, for a codex, and when the player comes',
      '## across it ("when"; known from the start without one, or only by an effect',
      '## with "by_effect"). Mechanics and quests\' starts work the same way.',
      `const LORE := ${gd(Object.fromEntries(ir.lore.map((l) => [l.ident.key, { name: l.name, text: l.notes, ...(l.byEffect ? { by_effect: true } : {}), ...(l.discoveredWhen ? { when: l.discoveredWhen } : {}) }])))}`,
      '',
      '## Each mechanic: when the player can use it ("when"; from the start without',
      '## one), and its tuning and other fields as written in the studio.',
      `const MECHANICS := ${gd(Object.fromEntries(ir.mechanics.map((m) => [m.ident.key, { name: m.name, text: m.notes, details: m.fields, ...(m.byEffect ? { by_effect: true } : {}), ...(m.availableWhen ? { when: m.availableWhen } : {}) }])))}`,
      '',
      '## A mechanic\'s field, such as its tuning ("" when it has none).',
      'static func mechanic_detail(mechanic_key: String, field: String) -> String:',
      '\treturn str(MECHANICS.get(mechanic_key, {}).get("details", {}).get(field, ""))',
      '',
      '## Put everything where it starts. Call once when a new game begins.',
      'static func reset(game: VCGSGameState) -> void:',
      '\tgame.flags.clear()',
      '\tgame.object_states.clear()',
      '\tfor collection in [game.items, game.arcs, game.chosen, game.solved, game.visited, game.fired, game.picked, game.quests, game.won, game.met, game.characters_met, game.found_items, game.locations_visited, game.used_objects, game.bookmarks, game.codex_notes, game.lore, game.mechanics]:',
      '\t\tcollection.clear()',
      '\tfor flag in FLAGS:',
      '\t\tgame.flags[flag] = FLAGS[flag]["initial"]',
      '\tfor object_key in OBJECTS:',
      '\t\tgame.object_states[object_key] = OBJECTS[object_key]',
      '\t# Quests with nothing to wait for start now; anything already true settles.',
      '\tgame._changed()',
      '',
      'static func fire(trigger_key: String, game: VCGSGameState) -> void:',
      '\tvar trigger: Dictionary = TRIGGERS.get(trigger_key, {})',
      '\tgame.fired[trigger_key] = true',
      '\tif trigger.has("sets"):',
      '\t\tgame.set_flag(trigger["sets"]["flag"], trigger["sets"]["value"])',
      '\tVCGSRuleEngine.apply(trigger.get("effects", []), game)',
      '\tgame.trigger_fired.emit(trigger_key)',
      '',
      'static func solve(puzzle_key: String, game: VCGSGameState) -> void:',
      '\tif game.is_solved(puzzle_key):',
      '\t\treturn',
      '\tgame.mark_solved(puzzle_key)',
      '\tVCGSRuleEngine.apply(PUZZLES.get(puzzle_key, {}).get("effects", []), game)',
      '',
      '## Complete a quest now, started or not, and pay its reward (once).',
      'static func complete_quest(quest_key: String, game: VCGSGameState) -> void:',
      '\tif game == null or game.quest_state(quest_key) == "done":',
      '\t\treturn',
      '\tgame.set_quest(quest_key, "done")',
      '\tVCGSRuleEngine.apply(QUESTS.get(quest_key, {}).get("reward", []), game)',
      '',
      '## Whether a win against this encounter counts now.',
      'static func can_win(encounter_key: String, game: VCGSGameState) -> bool:',
      '\treturn VCGSRuleEngine.check(ENCOUNTERS.get(encounter_key, {}).get("win_when", {}), game)',
      '',
      'static func win(encounter_key: String, game: VCGSGameState) -> void:',
      '\tif game:',
      '\t\tgame.mark_won(encounter_key)',
      '\tVCGSRuleEngine.apply(ENCOUNTERS.get(encounter_key, {}).get("on_win", []), game)',
      '',
      '## Do a loss\'s effects; returns what it leads to: "retry", "gameOver" or "carryOn".',
      'static func lose(encounter_key: String, game: VCGSGameState) -> String:',
      '\tvar encounter: Dictionary = ENCOUNTERS.get(encounter_key, {})',
      '\tVCGSRuleEngine.apply(encounter.get("on_lose", []), game)',
      '\treturn str(encounter.get("loss", "retry"))',
      '',
      '## A gate is open when its rule holds (a gate with no rule is open).',
      'static func gate_open(gate_key: String, game: VCGSGameState) -> bool:',
      '\treturn VCGSRuleEngine.check(GATES.get(gate_key, {}).get("rule", {}), game)',
      '',
      '## Fire every trigger, and solve every puzzle, whose rule now holds.',
      '## GameState calls this after each change unless auto_rules is off.',
      'static func settle(game: VCGSGameState) -> void:',
      '\tfor _round in 8:',
      '\t\tvar moved := false',
      '\t\tfor key in TRIGGERS:',
      '\t\t\tif TRIGGERS[key].has("rule") and not game.fired.has(key) and VCGSRuleEngine.check(TRIGGERS[key]["rule"], game):',
      '\t\t\t\tfire(key, game)',
      '\t\t\t\tmoved = true',
      '\t\tfor key in LORE:',
      '\t\t\tif not game.knows_lore(key) and not LORE[key].get("by_effect", false) and VCGSRuleEngine.check(LORE[key].get("when", {}), game):',
      '\t\t\t\tgame.discover_lore(key)',
      '\t\t\t\tmoved = true',
      '\t\tfor key in MECHANICS:',
      '\t\t\tif not game.has_mechanic(key) and not MECHANICS[key].get("by_effect", false) and VCGSRuleEngine.check(MECHANICS[key].get("when", {}), game):',
      '\t\t\t\tgame.enable_mechanic(key)',
      '\t\t\t\tmoved = true',
      '\t\tfor key in QUESTS:',
      '\t\t\tvar quest: Dictionary = QUESTS[key]',
      '\t\t\tvar state := game.quest_state(key)',
      '\t\t\tif state == "" and not quest.get("by_effect", false) and VCGSRuleEngine.check(quest.get("starts", {}), game):',
      '\t\t\t\tgame.set_quest(key, "active")',
      '\t\t\t\tmoved = true',
      '\t\t\telif state == "active" and quest.has("completes") and VCGSRuleEngine.check(quest["completes"], game):',
      '\t\t\t\tcomplete_quest(key, game)',
      '\t\t\t\tmoved = true',
      '\t\tfor key in PUZZLES:',
      '\t\t\tif PUZZLES[key].has("solved_when") and not game.is_solved(key) and VCGSRuleEngine.check(PUZZLES[key]["solved_when"], game):',
      '\t\t\t\tsolve(key, game)',
      '\t\t\t\tmoved = true',
      '\t\tif not moved:',
      '\t\t\treturn',
    ].join('\n'),
  );
  for (const f of ir.flags) {
    row({ id: f.id, label: f.name, symbol: 'state', group: 'Logic', generates: `Game state flag · ${f.values.join(' / ')}`, files: [rulesPath] }, f);
  }
  for (const t of ir.triggers) {
    row({ id: t.id, label: t.name, symbol: t.kind, group: 'Logic', generates: t.kind === 'gate' ? (t.rule ? 'Gate check' : 'Gate check (condition in words)') : t.rule ? 'Event trigger · fires by rule' : 'Event trigger', files: [rulesPath] }, t);
  }

  // Levels: a scene per level, its data, and a scene to walk it.
  const names: Record<string, string> = Object.fromEntries(
    [...ir.characters, ...ir.objects, ...ir.items, ...ir.locations, ...DESIGN_LISTS.flatMap((d) => ir[d.list]), ...ir.cinematics, ...ir.flags, ...ir.triggers, ...ir.choices, ...ir.scenes].map((x) => [x.ident.key, x.name]),
  );
  for (const level of ir.levels) {
    const scene = add(`levels/${level.key}.tscn`, levelTscn(level, root));
    const script = add(`levels/${level.key}.gd`, levelScript(level, names, gd, HEADER));
    const play = add(`levels/play_${level.key}.tscn`, playTscn(level, root));
    row({ id: level.guid, label: level.name, symbol: 'environment', group: 'World', generates: `Level scene · ${level.items.length} items (${level.export_name})`, files: [scene, script, play] }, level);
  }

  const readme = add(
    'README.md',
    [
      `# ${ir.project.name} — generated by VC Game Studio`,
      '',
      'Everything in this folder is rewritten on each export. Change the story in',
      'VC Game Studio, not these files.',
      '',
      '1. Add `res://addons/vcgs_runtime/game_state.gd` as an autoload named **GameState**.',
      '2. Put a scene\'s flow controller (`scenes/`) on a node, connect its signals, and call `start()`.',
      '3. Attach an object\'s script (`objects/`) to its node; call `interact("Pull")` from your input code.',
      '4. Call `VCGSRules.reset(GameState)` when a new game begins. Triggers and',
      '   puzzles then fire and solve themselves as their conditions come true, and',
      '   quests start and complete (GameState\'s `quest_started` and `quest_completed`).',
      '5. An encounter on a timeline asks for itself with `encounter_requested`: play',
      '   the fight, then call `win()` or `lose()` on the scene\'s flow controller.',
      '',
      '## Placeholder scenes',
      '',
      'Each story scene has a `scenes/<scene>.tscn` to run straight away: a stand-in',
      'for the location, its characters, objects (wired to their scripts), items,',
      'cinematics, puzzles and logic, and a plain on-screen player. Open one and',
      'press F6 (Run Current Scene) to play it; `play_story.tscn` plays the whole',
      'story from the Beginning, scene after scene. Press C (or the Codex button)',
      'for the codex: the quest log and the lore found so far.',
      '',
      'These scenes are rewritten on every export. To build the real thing, make an',
      'inherited scene from one (Scene > New Inherited Scene), save it outside this',
      'folder and add art there: it keeps the generated nodes and your changes both.',
      ...(DESIGN_LISTS.some((d) => ir[d.list].length)
        ? [
            '',
            '## Lore, quests, mechanics and encounters',
            '',
            '`lore/`, `quests/`, `mechanics/` and `encounters/` hold a Resource per',
            'definition (`VCGSLore`, `VCGSQuest`, `VCGSMechanic`, `VCGSEncounter`): its',
            'key, code, name, description and other fields, for a codex, a quest log or',
            'tuning to read with `load()`. All four also play: their rules are in',
            '`logic/rules.gd` (`LORE`, `MECHANICS`, `QUESTS`, `ENCOUNTERS`). GameState',
            'says when lore is discovered (`lore_discovered`, `known_lore()`) and when a',
            'mechanic becomes available (`mechanic_available`, `has_mechanic()`);',
            '`VCGSRules.mechanic_detail(key, "tuning")` reads a mechanic\'s tuning.',
          ]
        : []),
      ...(ir.levels.length
        ? [
            '',
            '## Levels',
            '',
            'Each level is `levels/<level>.tscn`: its items as nodes named by their export',
            'names, each tagged with `metadata/vcgs_guid` (the GUID never changes), with',
            'graybox meshes under `Proxy`, collision under `Collision`, and volumes as',
            '`Area3D`. The level\'s script (a `VCGSLevel`) runs its doors, pickups,',
            'volumes and rules on GameState. `levels/play_<level>.tscn` walks it at once',
            'with a plain first-person player (F6).',
            '',
            'Final art: set an item\'s *Final asset* in VC Game Studio to a scene or model',
            'here and it is placed as `Art` in place of the proxy. With *Final art locked*',
            'the proxy is never written, so re-export changes the item\'s place, collision',
            'and logic but never covers the art. To dress a level by hand, make an',
            'inherited scene from it outside this folder.',
          ]
        : []),
    ].join('\n'),
  );
  add(
    'vcgs_manifest.json',
    JSON.stringify(
      {
        generator: 'VC Game Studio',
        adapter: VERSION,
        engine: 'godot',
        project: ir.project,
        elements: elements.map((e) => ({ id: e.id, label: e.label, files: e.files, fingerprint: e.fingerprint })),
        // Spec §11.3: each level item's GUID, where it went in Godot, and what was sent.
        levels: ir.levels.map((l) => ({
          guid: l.guid,
          name: l.name,
          scene: `res://${root}/levels/${l.key}.tscn`,
          revision: l.revision,
          items: l.items.map((i) => ({ guid: i.guid, export_name: i.export_name, source: `${l.name} / ${i.name}`, engine_ref: `${l.export_name}/${i.export_name}`, revision: i.revision, replacement_locked: i.replacement_locked })),
        })),
      },
      null,
      2,
    ),
  );
  void readme;
  return { files, elements };
};

