/** A GDScript (and .tres) literal for plain data. */
export const gd = (value: unknown, indent = ''): string => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  const inner = `${indent}\t`;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((v) => `${inner}${gd(v, inner)},`).join('\n')}\n${indent}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined);
  if (entries.length === 0) return '{}';
  // Short records stay on one line so the tables read as tables.
  const flat = entries.every(([, v]) => v === null || typeof v !== 'object');
  if (flat && entries.length <= 8) return `{ ${entries.map(([k, v]) => `${JSON.stringify(k)}: ${gd(v)}`).join(', ')} }`;
  return `{\n${entries.map(([k, v]) => `${inner}${JSON.stringify(k)}: ${gd(v, inner)},`).join('\n')}\n${indent}}`;
};

const color = (hex: string): string => {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  const n = m ? parseInt(m[1]!, 16) : 0xd9607a;
  const c = (shift: number) => (((n >> shift) & 255) / 255).toFixed(3).replace(/\.?0+$/, '') || '0';
  return `Color(${c(16)}, ${c(8)}, ${c(0)}, 1)`;
};

/** A text Resource (.tres) for one of the runtime's Resource classes. */
const tres = (scriptClass: string, script: string, fields: Record<string, string>): string =>
  [
    `[gd_resource type="Resource" script_class="${scriptClass}" load_steps=2 format=3]`,
    '',
    `[ext_resource type="Script" path="res://${RUNTIME}/${script}" id="1_script"]`,
    '',
    '[resource]',
    'script = ExtResource("1_script")',
    ...Object.entries(fields).map(([k, v]) => `${k} = ${v}`),
    '',
  ].join('\n');

