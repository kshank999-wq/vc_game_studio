import type { GeneratedFile } from './engines';

/**
 * VCGSNav for Godot 4 (spec §19 navmesh): a level's navigation graph from the
 * handoff (IrNav) and the way across it, the same rules as the studio's
 * `findPath` and `nextOnWay`, so a patrol walks the same way in both.
 */
export const navRuntime = (runtime: string): GeneratedFile => ({
  path: `${runtime}/nav.gd`,
  kind: 'runtime',
  content: `${[
    '# VCGS Runtime for Godot 4.',
    'class_name VCGSNav',
    'extends RefCounted',
    '## A level\'s navigation graph (spec §19 navmesh): standable cells on a grid and which',
    '## reach which, and the way across it: A* over the cells, pulled straight wherever the',
    '## line between two points of it is clear. Points are in the level\'s space (x, y up,',
    '## z south). The same rules as the studio\'s Play Mode, so people walk round walls the',
    '## same way there and here. Doors count as open.',
    '',
    '## A way is planned again once its target has moved this far from where it was planned to.',
    'const REPLAN := 1.0',
    '',
    'var cell := 0.5',
    'var origin := Vector2.ZERO',
    'var cols := 0',
    'var rows := 0',
    'var step_up := 0.42',
    'var nodes := PackedVector3Array()',
    'var links: Array = []',
    '## Grid cell (row * cols + col) to the nodes standing in it.',
    'var at: Dictionary = {}',
    '## What a metre on each node counts for (Cost nav areas); empty when it is all ordinary ground (1).',
    'var costs := PackedFloat64Array()',
    '',
    '## The graph from a level\'s nav data (the generated level script\'s NAV); null for none.',
    'static func from_data(data: Dictionary) -> VCGSNav:',
    '\tif data.is_empty():',
    '\t\treturn null',
    '\tvar g := VCGSNav.new()',
    '\tg.cell = float(data.get("cell", 0.5))',
    '\tvar o: Array = data.get("origin", [0, 0])',
    '\tg.origin = Vector2(float(o[0]), float(o[1]))',
    '\tg.cols = int(data.get("cols", 0))',
    '\tg.rows = int(data.get("rows", 0))',
    '\tg.step_up = float(data.get("step_up", 0.42))',
    '\tvar flat: Array = data.get("nodes", [])',
    '\tfor i in range(0, flat.size() - 2, 3):',
    '\t\tvar n := Vector3(float(flat[i]), float(flat[i + 1]), float(flat[i + 2]))',
    '\t\tvar k := g.cell_of(n.x, n.z)',
    '\t\tif not g.at.has(k):',
    '\t\t\tg.at[k] = []',
    '\t\t(g.at[k] as Array).append(g.nodes.size())',
    '\t\tg.nodes.append(n)',
    '\tfor l in data.get("links", []):',
    '\t\tvar out: Array[int] = []',
    '\t\tfor m in l:',
    '\t\t\tout.append(int(m))',
    '\t\tg.links.append(out)',
    '\tfor c in data.get("costs", []):',
    '\t\tg.costs.append(float(c))',
    '\treturn g',
    '',
    'func cost_of(i: int) -> float:',
    '\treturn costs[i] if i < costs.size() else 1.0',
    '',
    'func cell_of(x: float, z: float) -> int:',
    '\tvar c := floori((x - origin.x) / cell)',
    '\tvar r := floori((z - origin.y) / cell)',
    '\treturn -1 if c < 0 or r < 0 or c >= cols or r >= rows else r * cols + c',
    '',
    'static func _flat(a: Vector3, b: Vector3) -> float:',
    '\treturn Vector2(b.x - a.x, b.z - a.z).length()',
    '',
    '## The node nearest a point: in its cell (the closest height), else the nearest in a few',
    '## cells round it; -1 for none. Height counts three times the plan: the floor you are on.',
    'func nearest(p: Vector3, reach: int = 4) -> int:',
    '\tvar c0 := floori((p.x - origin.x) / cell)',
    '\tvar r0 := floori((p.z - origin.y) / cell)',
    '\tvar best := -1',
    '\tvar score := INF',
    '\tfor ring in range(reach + 1):',
    '\t\tif best >= 0:',
    '\t\t\tbreak',
    '\t\tfor r in range(r0 - ring, r0 + ring + 1):',
    '\t\t\tfor c in range(c0 - ring, c0 + ring + 1):',
    '\t\t\t\tif maxi(absi(r - r0), absi(c - c0)) != ring or r < 0 or c < 0 or r >= rows or c >= cols:',
    '\t\t\t\t\tcontinue',
    '\t\t\t\tfor i in at.get(r * cols + c, []):',
    '\t\t\t\t\tvar n: Vector3 = nodes[i]',
    '\t\t\t\t\tvar s := _flat(n, p) + absf(n.y - p.y) * 3.0',
    '\t\t\t\t\tif s < score:',
    '\t\t\t\t\t\tscore = s',
    '\t\t\t\t\t\tbest = i',
    '\treturn best',
    '',
    '## Whether someone can walk straight from node a to node b: every half cell along the line',
    '## stands on a node near the height there, each leading to the next.',
    'func clear_line(a: int, b: int) -> bool:',
    '\tvar p: Vector3 = nodes[a]',
    '\tvar q: Vector3 = nodes[b]',
    '\tvar steps := maxi(1, ceili(_flat(p, q) / (cell * 0.5)))',
    '\tvar prev := a',
    '\t# Not straight across ground dearer than either end (a Cost nav area): round it, or through it as A* chose.',
    '\tvar cap := maxf(cost_of(a), cost_of(b)) + 0.000000001',
    '\tfor s in range(1, steps + 1):',
    '\t\tvar t := float(s) / float(steps)',
    '\t\tvar x := p.x + (q.x - p.x) * t',
    '\t\tvar z := p.z + (q.z - p.z) * t',
    '\t\tvar height: float = nodes[prev].y',
    '\t\tvar next := -1',
    '\t\tif s == steps:',
    '\t\t\tnext = b',
    '\t\telse:',
    '\t\t\tfor i in at.get(cell_of(x, z), []):',
    '\t\t\t\tif absf(nodes[i].y - height) <= step_up + 0.000001:',
    '\t\t\t\t\tnext = i',
    '\t\t\t\t\tbreak',
    '\t\tif next < 0 or cost_of(next) > cap:',
    '\t\t\treturn false',
    '\t\tif next == prev:',
    '\t\t\tcontinue',
    '\t\t# Straight on, or round a corner through a cell both sides of it reach.',
    '\t\tvar from: Array = links[prev]',
    '\t\tif not from.has(next):',
    '\t\t\tvar round := false',
    '\t\t\tfor m in from:',
    '\t\t\t\tif (links[m] as Array).has(next):',
    '\t\t\t\t\tround = true',
    '\t\t\t\t\tbreak',
    '\t\t\tif not round:',
    '\t\t\t\treturn false',
    '\t\tprev = next',
    '\treturn true',
    '',
    'static func _push(heap: Array, f: float, n: int) -> void:',
    '\theap.append([f, n])',
    '\tvar i := heap.size() - 1',
    '\twhile i > 0:',
    '\t\tvar up := (i - 1) >> 1',
    '\t\tif heap[up][0] <= heap[i][0]:',
    '\t\t\tbreak',
    '\t\tvar t = heap[up]',
    '\t\theap[up] = heap[i]',
    '\t\theap[i] = t',
    '\t\ti = up',
    '',
    'static func _pop(heap: Array) -> Array:',
    '\tvar top: Array = heap[0]',
    '\tvar last: Array = heap.pop_back()',
    '\tif not heap.is_empty():',
    '\t\theap[0] = last',
    '\t\tvar i := 0',
    '\t\twhile true:',
    '\t\t\tvar l := i * 2 + 1',
    '\t\t\tvar r := l + 1',
    '\t\t\tvar m := i',
    '\t\t\tif l < heap.size() and heap[l][0] < heap[m][0]:',
    '\t\t\t\tm = l',
    '\t\t\tif r < heap.size() and heap[r][0] < heap[m][0]:',
    '\t\t\t\tm = r',
    '\t\t\tif m == i:',
    '\t\t\t\tbreak',
    '\t\t\tvar t = heap[m]',
    '\t\t\theap[m] = heap[i]',
    '\t\t\theap[i] = t',
    '\t\t\ti = m',
    '\treturn top',
    '',
    '## The way from one place to another: the points to walk through, ending at the goal;',
    '## empty when there is no way there.',
    'func find_path(from: Vector3, to: Vector3) -> Array:',
    '\tvar start := nearest(from)',
    '\tvar goal := nearest(to)',
    '\tif start < 0 or goal < 0:',
    '\t\treturn []',
    '\tif start == goal:',
    '\t\treturn [to]',
    '\tvar g: Vector3 = nodes[goal]',
    '\tvar cost := { start: 0.0 }',
    '\tvar came := {}',
    '\tvar heap: Array = []',
    '\t_push(heap, _flat(nodes[start], g) + absf(nodes[start].y - g.y), start)',
    '\tvar done := {}',
    '\twhile not heap.is_empty():',
    '\t\tvar n: int = _pop(heap)[1]',
    '\t\tif n == goal:',
    '\t\t\tbreak',
    '\t\tif done.has(n):',
    '\t\t\tcontinue',
    '\t\tdone[n] = true',
    '\t\tvar here: Vector3 = nodes[n]',
    '\t\tfor m in links[n]:',
    '\t\t\tvar there: Vector3 = nodes[m]',
    '\t\t\t# A step counts its length at the mean cost of the ground either side.',
    '\t\t\tvar c: float = cost[n] + (_flat(here, there) + absf(there.y - here.y)) * (cost_of(n) + cost_of(m)) / 2.0',
    '\t\t\tif c < float(cost.get(m, INF)):',
    '\t\t\t\tcost[m] = c',
    '\t\t\t\tcame[m] = n',
    '\t\t\t\t_push(heap, c + _flat(there, g) + absf(there.y - g.y), m)',
    '\tif not came.has(goal):',
    '\t\treturn []',
    '\tvar chain: Array[int] = [goal]',
    '\twhile chain[0] != start:',
    '\t\tchain.push_front(int(came[chain[0]]))',
    '\t# Pull it straight: from each point, on to the farthest point of the chain it can see.',
    '\tvar out: Array = []',
    '\tvar i := 0',
    '\twhile i < chain.size() - 1:',
    '\t\tvar j := chain.size() - 1',
    '\t\twhile j > i + 1 and not clear_line(chain[i], chain[j]):',
    '\t\t\tj -= 1',
    '\t\tout.append(nodes[chain[j]])',
    '\t\ti = j',
    '\t# End at the goal itself when it is near its node (the node is the cell\'s middle).',
    '\tif _flat(to, g) <= cell and absf(to.y - g.y) <= step_up + 0.1:',
    '\t\tout[out.size() - 1] = to',
    '\treturn out',
    '',
    '## The next point to head for on the way from one place to another, keeping the way in',
    '## way (a Dictionary the caller keeps: route, aim, none): planned when there is none or',
    '## the target moved, its points dropped as they are reached. null: there is no way there.',
    'func next_on_way(way: Dictionary, from: Vector3, to: Vector3) -> Variant:',
    '\tif way.is_empty() or _flat(way["aim"], to) > REPLAN or absf((way["aim"] as Vector3).y - to.y) > 1.0:',
    '\t\tvar path := find_path(from, to)',
    '\t\tway["route"] = path',
    '\t\tway["aim"] = to',
    '\t\tway["none"] = path.is_empty()',
    '\tif way["none"]:',
    '\t\treturn null',
    '\tvar route: Array = way["route"]',
    '\twhile route.size() > 1 and _flat(route[0], from) < 0.05:',
    '\t\troute.pop_front()',
    '\treturn route[0] if route.size() > 1 else to',
  ].join('\n')}\n`,
});
